# Rewrite list.js with correct HTML entities in esc function

# HTML entity byte sequences - using ord() to avoid quoting issues
AMP = b'&'      # &
LT = b'<'       # <
GT = b'>'       # >
QUOT = b'"'     # "
APOS = bytes([39]) + b'#39;'  # ' -> '

js_content = (
    b"// Archive / list view: search + filters (external toolbar) -> /api/stories -> Grid.js (render + server-side paging).\n"
    b"// Design: Grid.js owns ONLY table rendering and pagination. Every filter lives in `state`; any change re-creates\n"
    b"// the grid (so paging always restarts at page 1 and a stale response can never overwrite a newer one).\n"
    b"(() => {\n"
    b"  const $ = (id) => document.getElementById(id);\n"
    b"  const sp0 = new URLSearchParams(location.search);\n"
    b"  const embed = sp0.get('embed') === '1';\n"
    b"  const esc = (s) => String(s ?? '').replace(/[&<>\\\"/']/g, (c) => ({\n"
    b"    '&': '" + AMP + b"', '<': '" + LT + b"', '>': '" + GT + b"', '\"': '" + QUOT + b"', \"'\": '" + APOS + b"'\n"
    b"  }[c]));\n"
    b"  // Server marks FTS hits with \\x01 ... \\x02 (see highlight() in search.js). Escape FIRST, then swap markers for <mark>.\n"
    b"  const hl = (marked, plain) => esc(marked ?? plain).replace(/\\x01/g, '<mark>').replace(/\\x02/g, '</mark>');\n"
    b"  const fmtDate = (d) => new Date(d + 'T00:00:00').toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });\n"
    b"\n"
    b"  // ---- theme (same contract as client.js: ?theme= wins, parent window may push updates, else follow the OS)\n"
    b"  const setTheme = (t) => { const c = document.documentElement.classList; c.remove('dark', 'light'); c.add(t === 'dark' ? 'dark' : 'light'); };\n"
    b"  setTheme(sp0.get('theme') ?? (matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light'));\n"
    b"  addEventListener('message', (e) => { if (e.source === window.parent && e.data && e.data.type === 'theme') setTheme(e.data.theme); });\n"
    b"\n"
    b"  // ---- filter state <-> URL (so a filtered view is bookmarkable and survives reload)\n"
    b"  const KEYS = ['q', 'mark', 'desk', 'subtopic', 'source', 'from', 'to', 'sort'];\n"
    b"  const state = Object.fromEntries(KEYS.map((k) => [k, sp0.get(k) ?? '']));\n"
    b"  state.tags = sp0.getAll('tag');\n"
    b"  function persist() {\n"
    b"    const p = new URLSearchParams(location.search); // keeps embed= / theme=\n"
    b"    for (const k of KEYS) state[k] ? p.set(k, state[k]) : p.delete(k);\n"
    b"    p.delete('tag'); state.tags.forEach((t) => p.append('tag', t));\n"
    b"    const qs = p.toString();\n"
    b"    history.replaceState(null, '', location.pathname + (qs ? '?' + qs : ''));\n"
    b"  }\n"
    b"  function apiUrl() {\n"
    b"    const p = new URLSearchParams();\n"
    b"    for (const k of KEYS) if (state[k]) p.set(k, state[k]);\n"
    b"    state.tags.forEach((t) => p.append('tag', t));\n"
    b"    return '/api/stories?' + p; // always contains '?', so Grid.js url fns can append with '&'\n"
    b"  }\n"
    b"\n"
    b"  // ---- cell renderers (all text goes through esc()/hl())\n"
    b"  const storyHtml = (r) => `\n"
    b"    <div class=\"story-cell\">\n"
    b"      <div class=\"story-meta\">${esc(r.desk)} &middot; ${esc(r.source)} &middot; ${esc(r.subtopic)}</div>\n"
    b"      <a class=\"story-head\" href=\"${esc(r.url)}\">${hl(r.h_headline, r.headline)}</a>\n"
    b"      <p class=\"story-blurb\">${hl(r.h_blurb, r.blurb)}</p>\n"
    b"      ${r.tags.length ? `<div class=\"story-tags\">${r.tags.map((t) => `<span>#${esc(t)}</span>`).join(' ')}</div>` : ''}\n"
    b"    </div>`;\n"
    b"  const actionsHtml = (r) => `\n"
    b"    <div class=\"story-actions\">\n"
    b"      <button type=\"button\" class=\"btn-save\" aria-pressed=\"${r.saved}\" data-action=\"save\" data-story-id=\"${r.story_id}\" title=\"Save story\">\n"
    b"        <span class=\"save-mark\" aria-hidden=\"true\"></span><span class=\"sr-only\">Save story</span></button>\n"
    b"      <button type=\"button\" class=\"btn-like\" aria-pressed=\"${r.liked}\" data-action=\"like\" data-story-id=\"${r.story_id}\" title=\"Like story\">\n"
    b"        <span class=\"like-mark\" aria-hidden=\"true\"></span><span class=\"sr-only\">Like story</span></button>\n"
    b"    </div>`;\n"
    b"\n"
    b"  // ---- grid\n"
    b"  const host = $('grid'), countEl = $('count');\n"
    b"  let grid = null, gen = 0;\n"
    b"  function render() {\n"
    b"    const mine = ++gen;\n"
    b"    persist();\n"
    b"    if (grid) { try { grid.destroy(); } catch { /* already gone */ } grid = null; }\n"
    b"    host.innerHTML = '';\n"
    b"    grid = new gridjs.Grid({\n"
    b"      columns: [\n"
    b"        { name: 'Date', width: '120px', formatter: (d) => fmtDate(d) },\n"
    b"        { name: 'Story', formatter: (r) => gridjs.html(storyHtml(r)) },\n"
    b"        { name: 'Mark', width: '90px', formatter: (r) => gridjs.html(actionsHtml(r)) },\n"
    b"      ],\n"
    b"      sort: false,\n"
    b"      search: false, // our own #q input drives the query\n"
    b"      className: { container: 'newspaper-grid' },\n"
    b"      language: {\n"
    b"        loading: 'Setting type\\u2026',\n"
    b"        noRecordsFound: 'No stories match these filters.',\n"
    b"        error: 'Could not load stories.',\n"
    b"        pagination: { previous: '\\u2039', next: '\\u203A', showing: 'Showing', results: () => 'stories' },\n"
    b"      },\n"
    b"      pagination: { limit: 25, server: { url: (prev, page, limit) => `${prev}&limit=${limit}&offset=${page * limit}` } },\n"
    b"      server: {\n"
    b"        url: apiUrl(),\n"
    b"        then: (d) => {\n"
    b"          if (mine === gen) countEl.textContent = `${d.total} ${d.total === 1 ? 'story' : 'stories'}`;\n"
    b"          return d.rows.map((r) => [r.date, r, r]); // object cells are fine: formatters receive them as-is\n"
    b"        },\n"
    b"        total: (d) => d.total,\n"
    b"      },\n"
    b"    }).render(host);\n"
    b"  }\n"
    b"\n"
    b"  // ---- like / save (same endpoint + guard header as client.js; optimistic with revert)\n"
    b"  async function toggle(btn) {\n"
    b"    const on = btn.getAttribute('aria-pressed') !== 'true';\n"
    b"    btn.setAttribute('aria-pressed', String(on));\n"
    b"    try {\n"
    b"      const r = await fetch(`/api/stories/${btn.dataset.storyId}/feedback`, {\n"
    b"        method: 'POST',\n"
    b"        headers: { 'Content-Type': 'application/json', 'X-Brief-Client': '1' },\n"
    b"        body: JSON.stringify({ action: btn.dataset.action, value: on }),\n"
    b"      });\n"
    b"      if (!r.ok) throw new Error(String(r.status));\n"
    b"    } catch { btn.setAttribute('aria-pressed', String(!on)); }\n"
    b"  }\n"
    b"  host.addEventListener('click', (e) => {\n"
    b"    const btn = e.target.closest('[data-action]');\n"
    b"    if (btn) { e.preventDefault(); toggle(btn); return; }\n"
    b"    const a = e.target.closest('a[href]');\n"
    b"    if (a && /^https?:/i.test(a.href) && !a.href.startsWith(location.origin)) {\n"
    b"      if (embed) { e.preventDefault(); parent.postMessage({ type: 'open-url', url: a.href }, '*'); }\n"
    b"      else { a.target = '_blank'; a.rel = 'noopener noreferrer'; }\n"
    b"    }\n"
    b"  });\n"
    b"\n"
    b"  // ---- toolbar wiring\n"
    b"  const debounce = (fn, ms) => { let t; return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); }; };\n"
    b"  const qEl = $('q');\n"
    b"  qEl.value = state.q;\n"
    b"  qEl.addEventListener('input', debounce(() => { state.q = qEl.value; render(); }, 250));\n"
    b"  $('filters').addEventListener('submit', (e) => e.preventDefault());\n"
    b"\n"
    b"  const markBtns = [...document.querySelectorAll('#mark [data-mark]')];\n"
    b"  const syncMark = () => markBtns.forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.mark === state.mark)));\n"
    b"  markBtns.forEach((b) => b.addEventListener('click', () => { state.mark = b.dataset.mark; syncMark(); render(); }));\n"
    b"  syncMark();\n"
    b"\n"
    b"  for (const k of ['desk', 'subtopic', 'source', 'from', 'to', 'sort']) {\n"
    b"    $(k).addEventListener('change', (e) => { state[k] = e.target.value; render(); });\n"
    b"    $(k).value = state[k];\n"
    b"  }\n"
    b"  $('reset').addEventListener('click', () => {\n"
    b"    KEYS.forEach((k) => { state[k] = ''; if ($(k)) $(k).value = ''; });\n"
    b"    state.tags = []; qEl.value = ''; syncMark(); drawTags(); render();\n"
    b"  });\n"
    b"\n"
    b"  // ---- facets: fill selects + tag chips (best effort; the list works without them)\n"
    b"  let tagFacet = [];\n"
    b"  function drawTags() {\n"
    b"    const all = [...new Set([...tagFacet.map((t) => t.value), ...state.tags])];\n"
    b"    const n = new Map(tagFacet.map((t) => [t.value, t.n]));\n"
    b"    $('tagbar').innerHTML = all.map((t) =>\n"
    b"      `<button type=\"button\" class=\"chip\" aria-pressed=\"${state.tags.includes(t)}\" data-tag=\"${esc(t)}\">#${esc(t)}${n.has(t) ? ` <small>${n.get(t)}</small>` : ''}</button>`).join('');\n"
    b"  }\n"
    b"  $('tagbar').addEventListener('click', (e) => {\n"
    b"    const b = e.target.closest('[data-tag]'); if (!b) return;\n"
    b"    const t = b.dataset.tag;\n"
    b"    state.tags = state.tags.includes(t) ? state.tags.filter((x) => x !== t) : [...state.tags, t].slice(0, 5);\n"
    b"    drawTags(); render();\n"
    b"  });\n"
    b"  fetch('/api/stories/facets').then((r) => r.json()).then((f) => {\n"
    b"    for (const k of ['desk', 'subtopic', 'source']) {\n"
    b"      const sel = $(k);\n"
    b"      const vals = f[k].map((x) => x.value);\n"
    b"      if (state[k] && !vals.includes(state[k])) vals.push(state[k]);\n"
    b"      const count = new Map(f[k].map((x) => [x.value, x.n]));\n"
    b"      sel.insertAdjacentHTML('beforeend', vals.map((v) => `<option value=\"${esc(v)}\">${esc(v)}${count.has(v) ? ` (${count.get(v)})` : ''}</option>`).join(''));\n"
    b"      sel.value = state[k];\n"
    b"    }\n"
    b"    tagFacet = f.tag; drawTags();\n"
    b"  }).catch(() => drawTags());\n"
    b"\n"
    b"  render();\n"
    b"})();\n"
)

with open('server/public/list.js', 'wb') as f:
    f.write(js_content)

print("Rewritten list.js with correct HTML entities")